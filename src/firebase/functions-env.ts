/**
 * Functions `.env` generation for `buncargo/firebase`: filters Firebase Cloud
 * Functions reserved keys, invalid identifiers, and excluded patterns, then
 * serializes values with single-quote safety for both `firebase-tools` and
 * `npm dotenv`, writing atomically with `0o600` permissions and persisting any
 * pre-existing user `.env` backup on disk so it survives a crash or SIGKILL.
 */

import { createHash, randomBytes } from "node:crypto";
import {
	chmodSync,
	existsSync,
	mkdirSync,
	readFileSync,
	renameSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { isRecord } from "hanzio";
import { matchesSecretPattern } from "../core/secrets/scope";

/** Marker line identifying a `.env` file managed by buncargo. */
export const BUNCARGO_FUNCTIONS_ENV_HEADER =
	"# Generated by buncargo (firebase functionsEnv), do not edit";

const RESERVED_PREFIXES = ["X_GOOGLE_", "EXT_", "FIREBASE_"] as const;
const RESERVED_KEYS = new Set([
	"CLOUD_RUNTIME_CONFIG",
	"ENTRY_POINT",
	"EVENTARC_CLOUD_EVENT_SOURCE",
	"GCP_PROJECT",
	"GCLOUD_PROJECT",
	"GOOGLE_CLOUD_PROJECT",
	"FUNCTION_TARGET",
	"FUNCTION_SIGNATURE_TYPE",
	"FUNCTION_NAME",
	"FUNCTION_REGION",
	"FUNCTION_TRIGGER_TYPE",
	"FUNCTION_MEMORY_MB",
	"FUNCTION_TIMEOUT_SEC",
	"FUNCTION_IDENTITY",
	"K_SERVICE",
	"K_REVISION",
	"K_CONFIGURATION",
	"PORT",
]);

const VALID_ENV_KEY = /^[A-Z_][A-Z0-9_]*$/;

/** Whether `key` is reserved by Firebase Cloud Functions and must not be written to `.env`. */
export function isReservedFunctionsEnvKey(key: string): boolean {
	return (
		RESERVED_KEYS.has(key) ||
		RESERVED_PREFIXES.some((prefix) => key.startsWith(prefix))
	);
}

/** Whether `key` is a valid Cloud Functions env identifier (`UPPER_SNAKE`). */
export function isValidFunctionsEnvKey(key: string): boolean {
	return VALID_ENV_KEY.test(key);
}

/**
 * Serialize one key/value pair so both `firebase-tools` and `npm dotenv`
 * decode it identically (multiline PEMs, JSON with double quotes, etc.).
 */
export function serializeFunctionsEnvEntry(key: string, value: string): string {
	// Single-quoted literal: both parsers take newlines, double quotes and
	// backslashes verbatim without un-escaping.
	if (!value.includes("'")) {
		return `${key}='${value}'`;
	}

	const escaped = value
		.replace(/\\/g, "\\\\")
		.replace(/\n/g, "\\n")
		.replace(/\r/g, "\\r")
		.replace(/"/g, '\\"');
	return `${key}="${escaped}"`;
}

export interface RenderFunctionsEnvOptions {
	/** Additional exact keys or glob patterns (`*`, `?`) to strip. */
	exclude?: readonly string[];
	/** Strip `GOOGLE_APPLICATION_CREDENTIALS` so functions stay on local emulators. */
	isolateCredentials?: boolean;
}

export interface RenderedFunctionsEnv {
	readonly content: string;
	readonly writtenKeys: readonly string[];
	readonly skippedKeys: readonly string[];
}

/** Filter and render a Functions `.env` file deterministically. */
export function renderFunctionsEnvFile(
	values: Readonly<Record<string, string | number | undefined>>,
	options: RenderFunctionsEnvOptions = {},
): RenderedFunctionsEnv {
	const exclude = [
		...(options.exclude ?? []),
		...(options.isolateCredentials ? ["GOOGLE_APPLICATION_CREDENTIALS"] : []),
	];
	const writtenKeys: string[] = [];
	const skippedKeys: string[] = [];
	const lines: string[] = [BUNCARGO_FUNCTIONS_ENV_HEADER];

	const keys = Object.keys(values).sort((a, b) => a.localeCompare(b));
	for (const key of keys) {
		const raw = values[key];
		if (raw === undefined) continue;
		const excluded = exclude.some((pattern) =>
			matchesSecretPattern(key, pattern),
		);
		if (
			excluded ||
			isReservedFunctionsEnvKey(key) ||
			!isValidFunctionsEnvKey(key)
		) {
			skippedKeys.push(key);
			continue;
		}
		lines.push(serializeFunctionsEnvEntry(key, String(raw)));
		writtenKeys.push(key);
	}

	return {
		content: `${lines.join("\n")}\n`,
		writtenKeys,
		skippedKeys,
	};
}

/** Extract `functions.source` from `firebase.json` (object or array), else `"functions"`. */
export function resolveFunctionsSourceDir(
	rawFirebaseConfig: Readonly<Record<string, unknown>>,
): string {
	const functions = rawFirebaseConfig.functions;
	if (
		isRecord(functions) &&
		typeof functions.source === "string" &&
		functions.source.trim()
	) {
		return functions.source.trim();
	}
	if (Array.isArray(functions)) {
		for (const entry of functions) {
			if (
				isRecord(entry) &&
				typeof entry.source === "string" &&
				entry.source.trim()
			) {
				return entry.source.trim();
			}
		}
	}
	return "functions";
}

export interface FunctionsEnvHandle {
	readonly path: string;
	restore(): void;
}

function writeAtomicFile(
	path: string,
	content: string | Buffer,
	mode: number,
): void {
	mkdirSync(dirname(path), { recursive: true });
	const tempPath = `${path}.${process.pid}.${randomBytes(6).toString("hex")}.tmp`;
	try {
		writeFileSync(tempPath, content, { mode, flag: "wx" });
		chmodSync(tempPath, mode);
		renameSync(tempPath, path);
	} catch (error) {
		rmSync(tempPath, { force: true });
		throw error;
	}
}

function backupPaths(
	backupDir: string,
	targetPath: string,
): { dataPath: string; metaPath: string } {
	const hash = createHash("sha256")
		.update(targetPath)
		.digest("hex")
		.slice(0, 16);
	return {
		dataPath: join(backupDir, `${hash}.bak`),
		metaPath: join(backupDir, `${hash}.mode`),
	};
}

function readDiskBackup(
	backupDir: string | undefined,
	targetPath: string,
): { content: Buffer; mode: number } | undefined {
	if (!backupDir) return undefined;
	const { dataPath, metaPath } = backupPaths(backupDir, targetPath);
	if (!existsSync(dataPath)) return undefined;
	try {
		const content = readFileSync(dataPath);
		let mode = 0o600;
		if (existsSync(metaPath)) {
			const parsed = Number.parseInt(readFileSync(metaPath, "utf8").trim(), 8);
			if (Number.isInteger(parsed) && parsed > 0) mode = parsed & 0o777;
		}
		return { content, mode };
	} catch {
		return undefined;
	}
}

/**
 * Write `content` to `targetPath` atomically with `0o600` permissions, backing
 * up any pre-existing user-authored file (on disk inside `backupDir` when
 * given, so a crash or SIGKILL cannot lose the original `.env`).
 */
export function writeFunctionsEnvFile(
	targetPath: string,
	content: string,
	options: { backupDir?: string } = {},
): FunctionsEnvHandle {
	const { backupDir } = options;
	let backup: { content: Buffer; mode: number } | undefined;

	if (existsSync(targetPath)) {
		const existing = readFileSync(targetPath);
		const text = existing.toString("utf8");
		if (!text.startsWith(BUNCARGO_FUNCTIONS_ENV_HEADER)) {
			const mode = statSync(targetPath).mode & 0o777;
			backup = { content: existing, mode };
			if (backupDir) {
				const { dataPath, metaPath } = backupPaths(backupDir, targetPath);
				writeAtomicFile(dataPath, existing, 0o600);
				writeAtomicFile(metaPath, mode.toString(8), 0o600);
			}
		} else {
			// A prior crashed run left our generated file on disk; recover its
			// persisted user backup so the next clean exit restores it.
			backup = readDiskBackup(backupDir, targetPath);
		}
	} else {
		backup = readDiskBackup(backupDir, targetPath);
	}

	writeAtomicFile(targetPath, content, 0o600);

	let restored = false;
	return {
		path: targetPath,
		restore: () => {
			if (restored) return;
			restored = true;
			try {
				const toRestore = backup ?? readDiskBackup(backupDir, targetPath);
				if (toRestore) {
					writeAtomicFile(targetPath, toRestore.content, toRestore.mode);
					if (backupDir) {
						const { dataPath, metaPath } = backupPaths(backupDir, targetPath);
						rmSync(dataPath, { force: true });
						rmSync(metaPath, { force: true });
					}
					return;
				}
				if (existsSync(targetPath)) {
					const current = readFileSync(targetPath, "utf8");
					if (current.startsWith(BUNCARGO_FUNCTIONS_ENV_HEADER)) {
						rmSync(targetPath, { force: true });
					}
				}
			} catch {
				// Best-effort cleanup on shutdown.
			}
		},
	};
}
